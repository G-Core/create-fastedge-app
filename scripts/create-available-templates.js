import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { FastEdgeTemplates } from "../src/create-app/resources.ts";

const availableTemplatesPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "create-app",
  "available-templates.ts",
);

let stringifiedTemplates = JSON.stringify(
  Object.keys(FastEdgeTemplates),
  null,
  2,
);
// Add "" as last item to satisfy "as const" assertion
stringifiedTemplates = stringifiedTemplates.replace(/\n\]$/, ',\n  ""\n]');

const content = `\
/* This file is auto-generated by scripts/create-available-templates.js
 * Run "pnpm build:available-templates" to update
 */
const availableTemplates = ${stringifiedTemplates} as const;
export { availableTemplates };
`;

fs.writeFile(availableTemplatesPath, content)
  .then(() => {
    console.log(
      `✅ Successfully created available-templates.js at ${availableTemplatesPath}`,
    );
  })
  .catch((error) => {
    console.error(
      `❌ Failed to create available-templates.js at ${availableTemplatesPath}:`,
      error,
    );
  });
